export function createInitialAdminStudentsState(): AdminStudentsState {
  return {
    students: sampleAdminStudents,
    totalCount: sampleAdminStudents.length,
    lastRefreshedAt: new Date().toISOString(),
  }
}

export function createInitialAdminReportsState(): AdminReportsState {
  const totalCompleted = sampleAdminReports.reduce((acc, r) => acc + r.totalStudentsCompleted, 0)
  const totalAttempts = sampleAdminReports.reduce((acc, r) => acc + r.totalQuizAttempts, 0)
  const validScores = sampleAdminReports
    .map((r) => r.averageQuizScorePercent)
    .filter((s): s is number => typeof s === 'number')
  const avg =
    validScores.length > 0
      ? Math.round((validScores.reduce((a, b) => a + b, 0) / validScores.length) * 10) / 10
      : null

  return {
    reports: sampleAdminReports,
    overallAverageScorePercent: avg,
    totalCompletedLabs: totalCompleted,
    totalQuizAttempts: totalAttempts,
    lastRefreshedAt: new Date().toISOString(),
  }
}
